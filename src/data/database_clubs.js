export const getClubInfo = (name) => {
  const club = resolveClub(name);
  const keys = club ? [club.name, ...(club.aliases || []), name] : [name];
  for (const key of keys) {
    if (clubsDatabase?.[key]) return clubsDatabase[key];
  }
  return null;
};

export default clubsDatabase;
